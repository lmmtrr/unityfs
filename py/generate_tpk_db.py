import os
import json
from collections import defaultdict
from UnityPy.helpers.Tpk import get_typetree, generate_node

CLASS_IDS = [
    1,
    4,
    21,
    23,
    28,
    33,
    43,
    48,
    49,
    74,
    83,
    90,
    91,
    95,
    114,
    115,
    128,
    135,
    136,
    137,
    142,
    213,
    223,
    225,
    329,
    687078895,
]


def previous_version(version):
    major, minor = version
    if minor > 0:
        return (major, minor - 1)
    return (major - 1, 65535)


def flatten_tree(node, nodes_list):
    level = node.m_Level
    type_str = node.m_Type
    name_str = node.m_Name
    byte_size = node.m_ByteSize
    meta_flag = node.m_MetaFlag
    is_array = getattr(node, "m_IsArray", False)
    if name_str == "offset" and (
        type_str in ("unsigned int", "int", "UInt32") or byte_size == 4
    ):
        type_str = "UInt64"
        byte_size = 8
    nodes_list.append((level, is_array, byte_size, meta_flag, type_str, name_str))
    for child in getattr(node, "m_Children", []):
        flatten_tree(child, nodes_list)


def main():
    tpk = get_typetree()
    class_information = tpk.ClassInformation
    db = defaultdict(list)
    for class_id in CLASS_IDS:
        ci = class_information.get(class_id)
        if not ci:
            continue
        by_minor = {}
        order = []
        for version, class_info in ci:
            key = (version.major, version.minor)
            if key not in by_minor:
                order.append(key)
            by_minor[key] = class_info
        version_trees = {}
        for key in order:
            class_info = by_minor[key]
            try:
                root = generate_node(class_info)
            except Exception as exc:
                print(f"warning: class {class_id} {key[0]}.{key[1]} skipped ({exc!r})")
                continue
            nodes = []
            flatten_tree(root, nodes)
            version_trees[key] = tuple(nodes)
        if not version_trees:
            continue
        sorted_vers = sorted(version_trees.keys())
        range_start = sorted_vers[0]
        curr_tree = version_trees[range_start]
        for i in range(1, len(sorted_vers)):
            v = sorted_vers[i]
            tree = version_trees[v]
            if tree != curr_tree:
                prev_v = sorted_vers[i - 1]
                db[class_id].append((range_start, prev_v, curr_tree))
                range_start = v
                curr_tree = tree
        last_v = sorted_vers[-1]
        db[class_id].append((range_start, last_v, curr_tree))
    rust_code = [
        "// Auto-generated by py/generate_tpk_db.py. DO NOT EDIT MANUALLY.\n",
        "use crate::serializedfile::TypeTreeNode;\n",
        "use crate::fallback_typetree::VersionRange;\n\n",
        "#[derive(Clone, Copy, Debug)]\n",
        "pub struct StaticTypeTreeNode {\n",
        "    pub level: u8,\n",
        "    pub is_array: bool,\n",
        "    pub byte_size: i32,\n",
        "    pub meta_flag: u32,\n",
        "    pub type_str: &'static str,\n",
        "    pub name_str: &'static str,\n",
        "}\n\n",
        "impl StaticTypeTreeNode {\n",
        "    pub fn to_type_tree_node(&self, index: i32) -> TypeTreeNode {\n",
        "        TypeTreeNode {\n",
        "            m_Version: 1,\n",
        "            m_Level: self.level as i8,\n",
        "            m_IsArray: self.is_array,\n",
        "            m_ByteSize: self.byte_size,\n",
        "            m_Index: index,\n",
        "            m_MetaFlag: self.meta_flag as i32,\n",
        "            m_Type: self.type_str.to_string(),\n",
        "            m_Name: self.name_str.to_string(),\n",
        "            m_TypeStrOffset: 0,\n",
        "            m_NameStrOffset: 0,\n",
        "            m_RefTypeHash: 0,\n",
        "        }\n",
        "    }\n",
        "}\n\n",
        "pub struct TpkDbEntry {\n",
        "    pub class_id: i32,\n",
        "    pub version_range: VersionRange,\n",
        "    pub nodes: &'static [StaticTypeTreeNode],\n",
        "}\n\n",
    ]
    array_definitions = []
    entries = []
    for class_id in sorted(db.keys()):
        class_entries = db[class_id]
        for idx_entry, ((min_maj, min_min), (max_maj, max_min), tree) in enumerate(
            class_entries
        ):
            array_name = f"NODES_{class_id}_{min_maj}_{min_min}_TO_{max_maj}_{max_min}"
            array_lines = [f"static {array_name}: &[StaticTypeTreeNode] = &[\n"]
            for lvl, is_arr, bsize, meta, tstr, nstr in tree:
                is_arr_str = "true" if is_arr else "false"
                t_json = json.dumps(tstr)
                n_json = json.dumps(nstr)
                array_lines.append(
                    f"    StaticTypeTreeNode {{ level: {lvl}, is_array: {is_arr_str}, byte_size: {bsize}, meta_flag: {meta}, type_str: {t_json}, name_str: {n_json} }},\n"
                )
            array_lines.append("];\n\n")
            array_definitions.append("".join(array_lines))
            is_first = idx_entry == 0
            is_last = idx_entry == len(class_entries) - 1
            min_maj_val = 0 if is_first else min_maj
            min_min_val = 0 if is_first else min_min
            if is_last:
                max_maj_val, max_min_val = 65535, 65535
            else:
                next_min = class_entries[idx_entry + 1][0]
                max_maj_val, max_min_val = previous_version(next_min)
            entries.append(
                f"    TpkDbEntry {{ class_id: {class_id}, version_range: VersionRange {{ min_major: {min_maj_val}, min_minor: {min_min_val}, max_major: {max_maj_val}, max_minor: {max_min_val} }}, nodes: {array_name} }},\n"
            )
    rust_code.extend(array_definitions)
    rust_code.append("pub static TPK_DATABASE: &[TpkDbEntry] = &[\n")
    rust_code.extend(entries)
    rust_code.append("];\n")
    base_dir = os.path.dirname(os.path.abspath(__file__))
    out_path = os.path.join(base_dir, "..", "src", "typetree_db.rs")
    with open(out_path, "w", encoding="utf-8") as f:
        f.writelines(rust_code)
    print(f"Successfully generated {out_path} with {len(entries)} TypeTree entries.")


if __name__ == "__main__":
    main()
